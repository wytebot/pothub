import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = async path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
test('Next.js server deployment wraps the full Pothub UI and routes APIs through the same runtime', async () => {
  const config = await read('next.config.mjs');
  const page = await read('pages/index.jsx');
  const api = await read('pages/api/[...path].js');
  const app = await read('src/ui/App.jsx');
  assert.doesNotMatch(config, /output:\s*'export'/);
  assert.match(page, /import\('\.\.\/src\/ui\/App\.jsx'\)/);
  assert.match(api, /export default async function pothubApi/);
  assert.match(api, /bodyParser: false/);
  assert.match(app, /\/api\/auth\/github/);
  assert.match(app, /signInWithRedirect\(firebaseAuth,new GoogleAuthProvider\(\)\)/);
  assert.match(app, /Connect GitHub/);
  assert.match(app, /Sign in with Google/);
  assert.match(app, /\/api\/billing\/checkout/);
});
test('Capacitor has a separate static-export build while Vercel keeps server APIs', async () => {
  const pkg = JSON.parse(await read('package.json'));
  const capBuilder = await read('scripts/build-capacitor.mjs');
  const config = await read('next.config.mjs');
  assert.match(pkg.scripts['build:cap'], /build-capacitor\.mjs/);
  assert.match(pkg.scripts['cap:sync'], /build:cap/);
  assert.match(capBuilder, /pages', 'api'/);
  assert.match(capBuilder, /output: 'export'/);
  assert.doesNotMatch(config, /output:\s*'export'/);
});

test('new deployments stamp the service worker and show a refresh prompt', async () => {
  const stamp = await read('scripts/stamp-service-worker.mjs');
  const notice = await read('src/ui/DeploymentUpdateNotice.jsx');
  const worker = await read('public/sw.js');
  assert.match(stamp, /VERCEL_DEPLOYMENT_ID/);
  assert.match(stamp, /pothub-shell-v6-\$\{safeId\}/);
  assert.match(notice, /Pothub has been updated/);
  assert.match(notice, /Refresh now/);
  assert.match(notice, /POTHUB_SKIP_WAITING/);
  assert.match(worker, /hadPreviousShell/);
});
test('frontend uses Next.js public environment variables rather than Vite import.meta', async () => {
  const app = await read('src/ui/App.jsx');
  const firebase = await read('src/lib/firebase.js');
  const video = await read('src/lib/video-adapters/gemini.js');
  assert.doesNotMatch(app + firebase + video, /import\.meta\.env/);
  assert.match(app, /process\.env\.NEXT_PUBLIC_API_BASE/);
  assert.doesNotMatch(app, /pdf\.worker\.mjs\?url/);
  const prep = await read('scripts/prepare-next-assets.mjs');
  const pkg = JSON.parse(await read('package.json'));
  assert.match(prep, /pdf\.worker\.mjs/);
  assert.match(pkg.scripts.build, /prepare-next-assets\.mjs/);
  assert.doesNotMatch(pkg.scripts.build, /vite/);
  assert.match(firebase, /process\.env\.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN/);
});
test('critical auth and health endpoints are isolated from the Express catch-all', async () => {
  const entry = await read('pages/api/[...path].js');
  assert.match(entry, /import\('\.\.\/\.\.\/server\/app\.js'\)/);
  assert.match(entry, /app\(req, res\)/);
  assert.match(entry, /externalResolver: true/);
  assert.match(entry, /status\(500\)/);
  const app = await read('src/ui/App.jsx');
  assert.match(app, /\/api\/auth\/github/);
  assert.match(app, /signInWithRedirect\(firebaseAuth,new GoogleAuthProvider\(\)\)/);
  assert.doesNotMatch(app, /\/api\/auth\/google-session/);
  assert.match(await read('pages/api/auth/github.js'), /github\.com\/login\/oauth\/authorize/);
  assert.match(await read('pages/api/auth/github/callback.js'), /setBrowserSession/);
  assert.match(await read('pages/api/auth/me.js'), /getSession\(req\)/);
  assert.match(await read('pages/api/health.js'), /firebaseAdminStatus/);
});
